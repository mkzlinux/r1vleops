// Generates supabase/seed.sql from the TypeScript catalog so DB prices match the site.
import { writeFileSync } from "node:fs";
import { SERVICES } from "../src/lib/catalog";
import { SEED_WORKERS } from "../src/lib/data/seed";

const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;
const arr = (xs: readonly string[]): string => `array[${xs.map(q).join(",")}]::text[]`;

const services = SERVICES.map((s, i) =>
  `(${q(s.id)}, ${q(s.departmentId)}, ${q(s.name)}, ${q(s.summary)}, ${s.priceUsd}, ${q(s.unit)}, ${s.deliveryDays}, ${arr(s.includes)}, ${i}, ${q(JSON.stringify(s.regional ?? {}))}::jsonb)`,
).join(",\n  ");
const workers = SEED_WORKERS.map((w) =>
  `(${q(w.id)}, ${q(w.kind)}, ${q(w.name)}, ${q(w.role)}, ${q(w.departmentId)}, ${q(w.email)}, ${q(w.status)})`,
).join(",\n  ");

writeFileSync("supabase/seed.sql", `-- Generated by scripts/gen-seed.ts. Do not edit by hand.
insert into public.services (id, department_id, name, summary, price_usd, unit, delivery_days, includes, sort, regional) values
  ${services}
on conflict (id) do update set regional = excluded.regional, price_usd = excluded.price_usd;

insert into public.workers (id, kind, name, role, department_id, email, status) values
  ${workers}
on conflict (id) do nothing;
`);
